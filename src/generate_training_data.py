def build_training_data():
    """生成顺序可重复、类别数量平衡的训练数据。"""

    rows = []
    for category, texts in CATEGORY_TEXTS.items():
        for text in texts:
            rows.append(
                {
                    "text": text,
                    "category": category,
                    "data_source": "合成演示数据",
                }
            )

    random_generator = random.Random(RANDOM_SEED)
    random_generator.shuffle(rows)

    for index, row in enumerate(rows, start=1):
        row["sample_id"] = index

    return pd.DataFrame(rows)[
        ["sample_id", "text", "category", "data_source"]
    ]


def main():
    """生成数据并保存到项目的数据目录。"""

    training_data = build_training_data()
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    training_data.to_csv(OUTPUT_PATH, index=False, encoding="utf-8-sig")

    print("训练数据生成完成")
    print(f"样本总数：{len(training_data)}")
    print("每类样本数：")
    print(training_data["category"].value_counts().sort_index().to_string())
    print(f"保存位置：{OUTPUT_PATH}")


if __name__ == "__main__":
    main()

